"""C++ emission (DESIGN.md 7.2, step 7): codelet text and the metadata table.

The codelet text is one .inl per lowering, written against the vocabulary
(src/isa/vocabulary.inl) and included inside each target's region after its vocabulary.
Region rules hold for it: force-inlined functions on vocabulary types only, no
standard-library templates, no lambdas (DESIGN.md 6.4). The calling convention is in
gen/README.md.
"""

from __future__ import annotations

import mpmath

from .codelet import Codelet, SplitCodelet
from .lower import Op

SPDX = (
    "// SPDX-FileCopyrightText: 2026 John C. Travers and contributors\n"
    "// SPDX-License-Identifier: Apache-2.0\n"
)
BANNER = (
    "// Generated by gen/fftn_gen. Do not edit: change the generator and regenerate\n"
    "// (gen/README.md).\n"
)

_BINARY = {"add", "sub", "addj", "subj"}


def literal_double(c: mpmath.mpf) -> str:
    return repr(float(c))


def literal_float(c: mpmath.mpf) -> str:
    with mpmath.workprec(24):
        f = float(+c)
    text = f"{f:.9g}"
    if not any(ch in text for ch in ".e"):
        text += ".0"
    return text + "F"


def _body(ops: tuple[Op, ...], indent: str) -> list[str]:
    names: dict[int, str] = {}
    temps = 0
    consts: dict[str, str] = {}
    decls: list[str] = []
    lines: list[str] = []

    def const(c: mpmath.mpf) -> str:
        d = literal_double(abs(c))
        if d not in consts:
            consts[d] = f"k{len(consts)}"
            decls.append(
                f"{indent}constexpr T {consts[d]} = gen_k<T>({d}, {literal_float(abs(c))});"
            )
        return ("-" if c < 0 else "") + consts[d]

    for op in ops:
        a = [names[v] for v in op.args]
        match op.kind:
            case "load":
                names[op.dst] = f"x{op.index}"
                lines.append(f"{indent}const cv<T> x{op.index} = in.get({op.index});")
                continue
            case "load_tw":
                names[op.dst] = f"w{op.index}"
                lines.append(f"{indent}const tw<T> w{op.index} = twid.get({op.index});")
                continue
            case "store":
                lines.append(f"{indent}out.put({op.index}, {a[0]});")
                continue
            case k if k in _BINARY:
                expr = f"{k}({a[0]}, {a[1]})"
            case "scale":
                expr = f"scale({a[0]}, {const(op.const)})"
            case "fmadd_r":
                expr = f"fmadd_r({a[0]}, {a[1]}, {const(op.const)})"
            case "mul" | "mulc":
                expr = f"{op.kind}({a[0]}, {a[1]})"
            case other:
                raise ValueError(f"cannot emit {other}")
        name = f"t{temps}"
        temps += 1
        names[op.dst] = name
        lines.append(f"{indent}const cv<T> {name} = {expr};")
    return decls + lines


_SIGNATURE = {
    "plain": (
        "template <class T, int Sign, class In, class Out>",
        "plain(const In& in, const Out& out)",
    ),
    "dit": (
        "template <class T, int Sign, class In, class Out, class Tw>",
        "dit(const In& in, const Out& out, const Tw& twid)",
    ),
    "dif": (
        "template <class T, int Sign, class In, class Out, class Tw>",
        "dif(const In& in, const Out& out, const Tw& twid)",
    ),
    "dif_head": (
        "template <class T, int Sign, class In, class Out, class Tw>",
        "dif_head(const In& in, const Out& out, const Tw& twid)",
    ),
    "plain_head": (
        "template <class T, int Sign, class In, class Out>",
        "plain_head(const In& in, const Out& out)",
    ),
}


def _summary(c: Codelet) -> str:
    k = c.counts
    return (
        f"{k.add_ops} add, {k.scale_ops} scale, {k.fma_ops} fmadd_r, {k.cmuls} cmul; "
        f"{k.flops_adds} + {k.flops_muls} real flops unfused; peak {c.live} live"
    )


def codelet_inl(codelets: list[Codelet]) -> str:
    by_radix: dict[int, dict[tuple[str, int], Codelet]] = {}
    for c in codelets:
        by_radix.setdefault(c.radix, {})[(c.variant, c.sign)] = c
    out = [
        SPDX,
        "//\n",
        BANNER,
        "//\n",
        "// Complex-register codelets (DESIGN.md 7): cdft<R> holds the R-point DFT in three\n",
        "// variants, each for Sign = -1 (forward) and +1 (backward):\n",
        "//\n",
        "//   plain(in, out)        out_k = sum_j in_j exp(Sign 2 pi i jk / R)\n",
        "//   dit(in, out, twid)    the same with in_j multiplied by t_j first (j >= 1)\n",
        "//   dif(in, out, twid)    the same with out_k multiplied by t_k after (k >= 1)\n",
        "//\n",
        "// t_j = twid.get(j) forward and its conjugate backward (twiddle tables hold\n",
        "// forward roots). in.get(j) returns a cv<T>, out.put(k, v) stores one and\n",
        "// twid.get(j) returns a tw<T>; all three are force-inlined members of the caller's\n",
        "// accessor types. Every output depends on every input, so in and out may address\n",
        "// the same memory. The even radices also hold two pruned variants (h = R/2),\n",
        "// for the edge passes of lines with stored runs:\n",
        "//\n",
        "//   dif_head(in, out, twid)  dif with in_j = 0 for j >= h, which it does not read\n",
        "//   plain_head(in, out)      plain storing out_0 .. out_{h-1} only\n",
        "//\n",
        "// Each loads every input it reads before its first store, so in and out may address\n",
        "// the same memory too. Included inside a region after its vocabulary; no include\n",
        "// guard. Calling convention and operation counts: gen/README.md.\n",
        "\n",
        "namespace {\n",
        "\n",
        "// A constant rounded once to T: the generator prints both roundings of its value.\n",
        "template <class T> FFTN_FORCE_INLINE constexpr T gen_k(double d, float f) {\n",
        "  if constexpr (sizeof(T) == sizeof(float)) {\n",
        "    return f;\n",
        "  } else {\n",
        "    return d;\n",
        "  }\n",
        "}\n",
        "\n",
        "template <std::size_t R> struct cdft;\n",
    ]
    for radix in sorted(by_radix):
        variants = by_radix[radix]
        out.append("\n")
        out.append(f"template <> struct cdft<{radix}> {{\n")
        out.append(f"  static constexpr std::size_t radix = {radix};\n")
        for variant in ("plain", "dit", "dif", "dif_head", "plain_head"):
            if (variant, -1) not in variants:
                continue  # a pruned variant of an odd radix
            fwd, bwd = variants[(variant, -1)], variants[(variant, 1)]
            tmpl, sig = _SIGNATURE[variant]
            out.append("\n")
            out.append(f"  // Forward: {_summary(fwd)}.\n")
            out.append(f"  // Backward: {_summary(bwd)}.\n")
            out.append(f"  {tmpl}\n")
            out.append(f"  static FFTN_FORCE_INLINE void {sig} {{\n")
            out.append(
                '    static_assert(Sign == -1 || Sign == 1, "Sign is -1 (forward) or +1");\n'
            )
            out.append("    if constexpr (Sign < 0) {\n")
            out.extend(line + "\n" for line in _body(fwd.ops, "      "))
            out.append("    } else {\n")
            out.extend(line + "\n" for line in _body(bwd.ops, "      "))
            out.append("    }\n")
            out.append("  }\n")
        out.append("};\n")
    out.append("\n} // namespace\n")
    return "".join(out)


_SPLIT_BINARY = {"add", "sub", "mul"}
_SPLIT_FUSED_K = {"fmaddk": "fmadd", "fnmaddk": "fnmadd", "fmsubk": "fmsub"}
_SPLIT_FUSED = {"fmadd", "fnmadd", "fmsub"}


def _split_body(ops: tuple[Op, ...], indent: str) -> list[str]:
    names: dict[int, str] = {}
    temps = 0
    consts: dict[str, str] = {}
    decls: list[str] = []
    lines: list[str] = []

    def const(c: mpmath.mpf) -> str:
        # Signed: a register constant has no negation for free.
        d = literal_double(c)
        if d not in consts:
            consts[d] = f"k{len(consts)}"
            decls.append(
                f"{indent}const rv<T> {consts[d]} = real::bcast(split_k<T>({d}, "
                f"{literal_float(c)}));"
            )
        return consts[d]

    loads = {
        "load_re": ("x", "r", "in.re"),
        "load_im": ("x", "i", "in.im"),
        "load_twr": ("w", "r", "twid.re"),
        "load_twi": ("w", "i", "twid.im"),
    }
    for op in ops:
        a = [names[v] for v in op.args]
        match op.kind:
            case k if k in loads:
                prefix, part, call = loads[k]
                names[op.dst] = f"{prefix}{op.index}{part}"
                lines.append(f"{indent}const rv<T> {names[op.dst]} = {call}({op.index});")
                continue
            case "store":
                lines.append(f"{indent}out.put({op.index}, {a[0]}, {a[1]});")
                continue
            case k if k in _SPLIT_BINARY:
                expr = f"real::{k}({a[0]}, {a[1]})"
            case "mulk":
                expr = f"real::mul({a[0]}, {const(op.const)})"
            case k if k in _SPLIT_FUSED_K:
                expr = f"real::{_SPLIT_FUSED_K[k]}({a[0]}, {const(op.const)}, {a[1]})"
            case k if k in _SPLIT_FUSED:
                expr = f"real::{k}({a[0]}, {a[1]}, {a[2]})"
            case "neg":
                expr = f"real::neg({a[0]})"
            case other:
                raise ValueError(f"cannot emit split {other}")
        name = f"t{temps}"
        temps += 1
        names[op.dst] = name
        lines.append(f"{indent}const rv<T> {name} = {expr};")
    return decls + lines


_SPLIT_SIGNATURE = {
    "plain": ("template <class T, class In, class Out>", "plain(const In& in, const Out& out)"),
    "dif": (
        "template <class T, class In, class Out, class Tw>",
        "dif(const In& in, const Out& out, const Tw& twid)",
    ),
}


def _split_summary(c: SplitCodelet) -> str:
    k = c.counts
    return (
        f"{k.adds} add, {k.muls} mul, {k.fmas} fused, {k.negs} neg; "
        f"{k.flops_adds} + {k.flops_muls} real flops unfused; peak {c.live} live"
    )


def split_codelet_inl(codelets: list[SplitCodelet]) -> str:
    by_radix: dict[int, dict[str, SplitCodelet]] = {}
    for c in codelets:
        by_radix.setdefault(c.radix, {})[c.variant] = c
    out = [
        SPDX,
        "//\n",
        BANNER,
        "//\n",
        "// Split codelets (DESIGN.md 7.2, step 4): sdft<R> holds the forward R-point DFT on\n",
        "// separate real and imaginary registers of the real vocabulary (rv<T>, W reals each,\n",
        "// one line per lane), in two variants:\n",
        "//\n",
        "//   plain(in, out)        out_k = sum_j in_j exp(-2 pi i jk / R)\n",
        "//   dif(in, out, twid)    the same with out_k multiplied by w_k after (k >= 1)\n",
        "//\n",
        "// in.re(j) and in.im(j) return the parts of leg j, out.put(k, re, im) stores leg k,\n",
        "// twid.re(k) and twid.im(k) return the parts of the forward twiddle w_k; all are\n",
        "// force-inlined members of the caller's accessor types, each called once per leg.\n",
        "// The backward transform is the forward one with the parts exchanged on loading and\n",
        "// on storing, with the same forward twiddles (gen/fftn_gen/split.py). Every output\n",
        "// depends on every input, so in and out may address the same memory. Included\n",
        "// inside a region after its vocabulary; no include guard. Calling convention and\n",
        "// operation counts: gen/README.md.\n",
        "\n",
        "namespace {\n",
        "\n",
        "// A constant rounded once to T: the generator prints both roundings of its value.\n",
        "template <class T> FFTN_FORCE_INLINE constexpr T split_k(double d, float f) {\n",
        "  if constexpr (sizeof(T) == sizeof(float)) {\n",
        "    return f;\n",
        "  } else {\n",
        "    return d;\n",
        "  }\n",
        "}\n",
        "\n",
        "template <std::size_t R> struct sdft;\n",
    ]
    for radix in sorted(by_radix):
        variants = by_radix[radix]
        out.append("\n")
        out.append(f"template <> struct sdft<{radix}> {{\n")
        out.append(f"  static constexpr std::size_t radix = {radix};\n")
        for variant in ("plain", "dif"):
            c = variants[variant]
            tmpl, sig = _SPLIT_SIGNATURE[variant]
            out.append("\n")
            out.append(f"  // {_split_summary(c)}.\n")
            out.append(f"  {tmpl}\n")
            out.append(f"  static FFTN_FORCE_INLINE void {sig} {{\n")
            out.extend(line + "\n" for line in _split_body(c.ops, "    "))
            out.append("  }\n")
        out.append("};\n")
    out.append("\n} // namespace\n")
    return "".join(out)


def _rows(codelets: list[Codelet]) -> list[str]:
    rows = []
    for c in codelets:
        k = c.counts
        rows.append(
            f"    {{{c.radix}, variant::{c.variant}, {c.sign}, lowering::complex_register, "
            f"{c.twiddles}, {k.adds}, {k.muls}, {k.fmas}, {k.cmuls}, "
            f"{k.vector_ops}, {c.live}}},\n"
        )
    return rows


def metadata_hpp(
    codelets: list[Codelet], split: list[SplitCodelet], pruned: list[Codelet] = ()
) -> str:
    radices = sorted({c.radix for c in codelets})
    split_radices = sorted({c.radix for c in split})
    pruned_radices = sorted({c.radix for c in pruned})
    split_rows = []
    for c in split:
        k = c.counts
        split_rows.append(
            f"    {{{c.radix}, variant::{c.variant}, {c.twiddles}, {k.adds}, {k.muls}, "
            f"{k.fmas}, {k.negs}, {k.vector_ops}, {c.live}}},\n"
        )
    rows = _rows(codelets)
    return "".join(
        [
            SPDX,
            "//\n",
            BANNER,
            "//\n",
            "// The metadata of the generated codelets (DESIGN.md 7.2, step 7): one entry per\n",
            "// radix, variant, direction and lowering, in that order. The planner's cost model,\n",
            "// the kernel registry and the tests read this table; nothing else lists radices.\n",
            '// Field meanings are in gen/README.md ("Metadata").\n',
            "#pragma once\n",
            "\n",
            "#include <cstddef>\n",
            "#include <cstdint>\n",
            "\n",
            "namespace fftn::inline v0::detail::gen {\n",
            "\n",
            "// dif_head and plain_head are the pruned variants (pruned_codelets below).\n",
            "enum class variant : std::uint8_t { plain, dit, dif, dif_head, plain_head };\n",
            "enum class lowering : std::uint8_t { complex_register, split };\n",
            "\n",
            "struct codelet_info {\n",
            "  std::uint8_t radix;\n",
            "  variant kind;\n",
            "  std::int8_t sign; // -1 forward, +1 backward\n",
            "  lowering form;\n",
            "  std::uint8_t twiddles; // twiddles read: R - 1, or 0 for plain\n",
            "  // Real arithmetic on a fused target, complex multiplies by twiddles apart.\n",
            "  std::uint16_t adds;\n",
            "  std::uint16_t muls;\n",
            "  std::uint16_t fmas;\n",
            "  std::uint16_t cmuls;   // complex multiplies by twiddles (mul, mulc)\n",
            "  std::uint16_t vops;    // vocabulary operations, loads and stores apart\n",
            "  std::uint16_t live;    // peak live values (complex and twiddle registers)\n",
            "};\n",
            "\n",
            f"inline constexpr std::size_t codelet_count = {len(codelets)};\n",
            "// A C array: ISA regions read it, and they use no standard-library templates.\n",
            "inline constexpr codelet_info codelets[codelet_count] = {\n",
            *rows,
            "};\n",
            "\n",
            f"inline constexpr std::size_t radix_count = {len(radices)};\n",
            "inline constexpr std::uint8_t radices[radix_count] = {",
            ", ".join(map(str, radices)),
            "};\n",
            "\n",
            "// The pruned codelets (DESIGN.md 12.1, task 5.1e): one entry per even radix,\n",
            "// pruned variant and direction, in that order. dif_head reads inputs 0 .. R/2 - 1\n",
            "// (the others are known zero), plain_head stores outputs 0 .. R/2 - 1 (the others\n",
            "// are not wanted); the counts are the pruned codelet's.\n",
            f"inline constexpr std::size_t pruned_codelet_count = {len(pruned)};\n",
            "inline constexpr codelet_info pruned_codelets[pruned_codelet_count] = {\n",
            *_rows(list(pruned)),
            "};\n",
            "\n",
            f"inline constexpr std::size_t pruned_radix_count = {len(pruned_radices)};\n",
            "inline constexpr std::uint8_t pruned_radices[pruned_radix_count] = {",
            ", ".join(map(str, pruned_radices)),
            "};\n",
            "\n",
            "// The split codelets (lowering::split, src/gen/split_codelets.inl): one entry per\n",
            "// radix and variant, forward only (the backward transform exchanges the real and\n",
            "// imaginary parts). Counts are real-register operations, each on W reals: add and\n",
            "// sub; mul (by a constant or a twiddle part); fused multiply-adds; neg.\n",
            "struct split_codelet_info {\n",
            "  std::uint8_t radix;\n",
            "  variant kind;\n",
            "  std::uint8_t twiddles; // twiddles read: R - 1, or 0 for plain\n",
            "  std::uint16_t adds;\n",
            "  std::uint16_t muls;\n",
            "  std::uint16_t fmas;\n",
            "  std::uint16_t negs;\n",
            "  std::uint16_t vops; // all of the above\n",
            "  std::uint16_t live; // peak live real values\n",
            "};\n",
            "\n",
            f"inline constexpr std::size_t split_codelet_count = {len(split)};\n",
            "inline constexpr split_codelet_info split_codelets[split_codelet_count] = {\n",
            *split_rows,
            "};\n",
            "\n",
            f"inline constexpr std::size_t split_radix_count = {len(split_radices)};\n",
            "inline constexpr std::uint8_t split_radices[split_radix_count] = {",
            ", ".join(map(str, split_radices)),
            "};\n",
            "\n",
            "} // namespace fftn::inline v0::detail::gen\n",
        ]
    )
