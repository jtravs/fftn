// Tolerances derived before a test runs from the precision, the length and the algorithm's
// error bound (DESIGN.md 15.2).
//
// Metrics. For a computed transform Y of an input whose exact transform is X:
//   rms error  ||Y - X||_2   / ||X||_2      (relative RMS error)
//   max error  ||Y - X||_inf / ||X||_inf    (largest error, relative to the largest output)
//
// Model. A transform built from stable butterflies with twiddles accurate to a few units of
// roundoff has a worst-case relative error of order eps * log2 n (Higham, Accuracy and
// Stability of Numerical Algorithms, section 24.1). Rounding errors behave like independent
// random variables, so the RMS error grows like eps * sqrt(log2 n) (Schatzman, SIAM J. Sci.
// Comput. 17, 1996), and the largest of the n errors, relative to the largest output, adds a
// factor of about sqrt(2 ln n), which is of order sqrt(log2 n) again. Hence, with
// L = max(1, log2 n) and eps the machine epsilon of the type under test:
//
//   rms tolerance = c_rms * eps * sqrt(L)
//   max tolerance = c_max * eps * L
//
// For a 2-D transform, n is the number of points in a plane: the errors of the two axes add
// in quadrature, and log2(ny nx) = log2 ny + log2 nx.
//
// Constants. Measured against the quadruple-precision reference on random inputs (Apple
// M5 Max, Clang 23; double and float alike):
//   rms / (eps sqrt L): FFTW 0.28-0.34 at powers of two up to 2^18, up to 0.9 at lengths
//                       with large prime factors; the naive DFT below 0.42
//   max / (eps L):      FFTW 0.07-0.11 at powers of two, up to 0.43 at awkward lengths;
//                       the naive DFT below 0.25
// (The prototype's 4-5e-16 in double at its largest sizes is about 0.4 eps sqrt L, in the
// same range.) c_rms = c_max = 3 puts the tolerances 3 to 10 times above the RMS errors
// and 7 to 40 times above the largest ones. Over the analytic and reference suites the
// largest error/tolerance ratio seen is 0.56 (FFTW, float, a tone at n = 417), so a correct
// FFT passes with a margin of about two at its least accurate lengths, while DESIGN.md
// 15.2's "within about 10 times of the measured error" holds at regular lengths.
//
// What these tolerances catch, and what no tolerance can. Wrong signs, misplaced bins,
// wrong scaling and dropped elements give errors of order one. Twiddle errors that grow
// with the index, as when a table is generated by powers or a recurrence from a base
// twiddle that is one ulp off, give w^m an error of about m ulps and the output an RMS
// error of about 0.29 eps n: measured at 2.4 times the RMS tolerance at n = 64, 27 times at
// n = 1024 and 110 times at n = 4096, and (estimated) below it at a dozen points. A single
// table entry one ulp off, on the other hand, changes the output by no more than the
// rounding every correct implementation makes, at any n, so no output tolerance can see it;
// twiddle tables are checked entry by entry against the reference instead
// (reference_checks::twiddle_table).

#pragma once

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <limits>
#include <numbers>

namespace fftn::test {

// An algorithm's error constants (see above).
struct error_bound {
  double rms = 0.0;
  double max = 0.0;
};

// Stable butterflies (any FFT with accurate twiddles) and the naive DFT with pairwise sums.
inline constexpr error_bound stable_fft_bound{.rms = 3.0, .max = 3.0};

struct tolerance {
  double rms = 0.0;
  double max = 0.0;

  // A check that compares two computed transforms carries the error of both.
  tolerance operator+(const tolerance& o) const { return {.rms = rms + o.rms, .max = max + o.max}; }
  tolerance operator*(double s) const { return {.rms = rms * s, .max = max * s}; }
};

inline double log2_length(std::size_t n) {
  return std::max(1.0, std::log2(static_cast<double>(std::max<std::size_t>(n, 1))));
}

// Bluestein (DESIGN.md 15.2): a transform of n = s Q points whose factor Q goes through a
// cyclic convolution of length M (2Q - 1 <= M < 4Q). Its error is that of three transforms
// of s M points in sequence: the forward transform and the inverse at execution, and the
// kernel spectrum computed at plan time (in double, so for double plans it counts in
// full); the two chirp multiplications add a rounding each, which is below one transform's.
// Independent errors add in quadrature, so with L' = log2(s M) <= log2 n + 2 the model
// gives
//
//   rms tolerance = c_rms * eps * sqrt(3 L')
//   max tolerance = c_max * eps * sqrt(3) L'
//
// with the constants of stable_fft_bound. Expressed as constants on L = log2 n, as
// derived_tolerance takes them, they are c sqrt(3 L' / L) and c sqrt(3) L' / L, using the
// upper end L' = L + 2. Measured (Apple M5 Max, neon_fcma, random inputs against the
// quadruple-precision reference, primes and products with large primes from 17 to 10403):
// rms / (eps sqrt L) 0.42-0.83 and max / (eps L) 0.13-0.37, so the Bluestein lengths sit
// within stable_fft_bound already (3.6 and 8 times below it); the derived bound is 1.8 to
// 2.1 times looser in RMS and 1.8 to 2.6 times in the largest error, tending to sqrt(3)
// for long lines.
inline error_bound bluestein_bound(std::size_t n) {
  const double l = log2_length(n);
  const double wider = (l + 2.0) / l;
  return {.rms = stable_fft_bound.rms * std::sqrt(3.0 * wider),
          .max = stable_fft_bound.max * std::numbers::sqrt3 * wider,};
}

// Whether n has a prime factor above the codelets' 16, which FFTN's planner sends through
// Bluestein on every profile (src/planner/rules.cpp).
inline bool has_large_prime_factor(std::size_t n) {
  for (std::size_t p = 2; p <= n / p; ++p) {
    while (n % p == 0) {
      if (p > 16) {
        return true;
      }
      n /= p;
    }
  }
  return n > 16;
}

// FFTN's bound for a transform of n points: Bluestein's where the planner uses it.
inline error_bound fftn_bound(std::size_t n) {
  return has_large_prime_factor(n) ? bluestein_bound(n) : stable_fft_bound;
}

template <class T> tolerance derived_tolerance(std::size_t n, const error_bound& bound) {
  const double eps = std::numeric_limits<T>::epsilon();
  const double l = log2_length(n);
  return {.rms = bound.rms * eps * std::sqrt(l), .max = bound.max * eps * l};
}

// The error that rounding an analytic input to T adds to a check whose expected output is
// the transform of the unrounded input: at most eps / sqrt(2) relative in both metrics,
// since the DFT preserves the 2-norm up to a factor sqrt(n) and maps the infinity-norm of
// the input error to at most its 1-norm.
template <class T> tolerance input_rounding() {
  const double eps = std::numeric_limits<T>::epsilon();
  return {.rms = eps, .max = eps};
}

} // namespace fftn::test
